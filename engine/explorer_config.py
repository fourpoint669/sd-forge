"""Per-project explorer.toml: which metrics headline the page and which charts it draws.

Generated with defaults on first build (no questions asked) and committed with the project; edit and rebuild to change
the page. Defaults: decision metric = [policy].objective; headline = the decision metric plus up to three other
[montecarlo] metrics read at the same time; charts = the decision metric's variable (outcome), then small-multiple
grids of every stock, every flow and the remaining [model].key_outputs, each ordered by sector then name. Large models
(more than COLLAPSE_ABOVE such charts) instead get one open grid of the [model].key_outputs and one collapsed grid per
sector holding that sector's remaining stocks and flows.
Every name is checked against validation.toml (unknown names fail the build).
"""
import json
import os
import tomllib

HEADER = ("# sd-explorer page settings. Generated by engine/explorer_config.py with defaults (no questions asked);\n"
          "# edit and rebuild (python -I engine/build_explorer.py <project dir>) to change the page.\n"
          "# Every name must exist in validation.toml: metrics in [montecarlo].metrics, variables in the model.\n")


COLLAPSE_ABOVE = 12


class ConfigError(Exception):
    """explorer.toml names something that does not exist."""


def _q(s):
    return json.dumps(s, ensure_ascii=False)


def _ordered(names, spec):
    sectors = list(spec.get("sectors", {}))
    sec = {v: i for i, (s, vs) in enumerate(spec.get("sectors", {}).items()) for v in vs}
    return sorted(names, key=lambda n: (sec.get(n, len(sectors)), n.lower()))


def default_config(spec, kinds):
    """TOML text with the default page settings. kinds: {variable name: stock|flow|auxiliary|parameter|constant}."""
    metrics = spec.get("montecarlo", {}).get("metrics", [])
    by_name = {m["name"]: m for m in metrics}
    pol = spec.get("policy", {})
    objective = pol.get("objective") or (metrics[0]["name"] if metrics else None)
    if objective not in by_name:
        raise ConfigError(f"no decision metric: [policy].objective '{objective}' is not a [montecarlo] metric")
    obj = by_name[objective]
    same_time = [m["name"] for m in metrics if m["name"] != objective and m["stat"] == "value_at"
                 and obj["stat"] == "value_at" and m["time"] == obj["time"]]
    headline = [objective] + same_time[:3]
    stocks = _ordered([k for k, v in kinds.items() if v == "stock"], spec)
    flows = _ordered([k for k, v in kinds.items() if v == "flow"], spec)
    rest = [k for k in spec["model"].get("key_outputs", []) if k not in stocks and k not in flows and k != obj["var"]]
    lines = [HEADER, "[decision]", f"metric = {_q(objective)}",
             f"maximize = {'true' if pol.get('maximize', True) else 'false'}",
             "headline = [" + ", ".join(_q(h) for h in headline) + "]", ""]
    charts = [("outcome", "outcome", obj["var"] + " over time", [obj["var"]], True)]
    if len(stocks) + len(flows) + len(rest) <= COLLAPSE_ABOVE:
        charts += [("stocks", "grid", "Stocks", stocks, True), ("flows", "grid", "Flows", flows, True)]
        if rest:
            charts.append(("outputs", "grid", "Other key outputs", rest, True))
    else:
        key = [k for k in spec["model"].get("key_outputs", []) if k != obj["var"]]
        charts.append(("key", "grid", "Key outputs", key, True))
        left = [v for v in stocks + flows if v not in key and v != obj["var"]]
        groups = list(spec.get("sectors", {}).items()) + [("other", [])]
        placed = set()
        for sector, members in groups:
            vs = [v for v in _ordered(left, spec) if (v in members or (sector == "other" and v not in placed))]
            placed |= set(vs)
            if vs:
                charts.append(("sector:" + sector, "grid", sector, vs, False))
    for cid, kind, title, vs, is_open in charts:
        lines += ["[[charts]]", f"id = {_q(cid)}", f"kind = {_q(kind)}", f"title = {_q(title)}",
                  f"open = {'true' if is_open else 'false'}", "vars = [" + ", ".join(_q(v) for v in vs) + "]", ""]
    return "\n".join(lines)


def load_config(project_dir, spec, kinds):
    """Read projects/<m>/explorer.toml (writing the defaults first if it is absent) and check every name."""
    path = os.path.join(project_dir, "explorer.toml")
    names = set(kinds)
    if not os.path.exists(path):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(default_config(spec, kinds))
    cfg = tomllib.load(open(path, "rb"))
    metrics = {m["name"] for m in spec.get("montecarlo", {}).get("metrics", [])}
    dec = cfg.get("decision", {})
    bad = [m for m in [dec.get("metric")] + list(dec.get("headline", [])) if m not in metrics]
    bad += [v for c in cfg.get("charts", []) for v in c.get("vars", []) if v not in names]
    if bad or not cfg.get("charts"):
        raise ConfigError(f"explorer.toml: unknown names {bad}" if bad else "explorer.toml: no [[charts]]")
    return cfg
